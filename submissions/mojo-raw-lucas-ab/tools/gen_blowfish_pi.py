"""Generates src/blowfish_pi.mojo: Blowfish's initial P-array and S-boxes, which are the hexadecimal digits of pi's
fractional part (18 + 4 * 256 32-bit words), computed here exactly with integer arithmetic (Machin's formula).

    python3 tools/gen_blowfish_pi.py > src/blowfish_pi.mojo
"""

WORDS = 18 + 4 * 256
BITS = WORDS * 32
GUARD = 64


def arctan_inv(x, bits):
    """arctan(1/x) * 2**bits, as an integer (error < number of terms)."""
    one = 1 << bits
    total = term = one // x
    x2 = x * x
    n = 1
    sign = -1
    while term:
        term //= x2
        total += sign * (term // (2 * n + 1))
        sign = -sign
        n += 1
    return total


def pi_fraction_bits(bits):
    b = bits + GUARD
    pi = 16 * arctan_inv(5, b) - 4 * arctan_inv(239, b)  # pi * 2**b
    frac = pi - (3 << b)
    return frac >> GUARD  # the first `bits` bits of pi's fractional part


frac = pi_fraction_bits(BITS)
words = [(frac >> (BITS - 32 * (i + 1))) & 0xFFFFFFFF for i in range(WORDS)]

# Anchors everyone who has implemented Blowfish knows: first and last P entries, first S0, last S3.
assert words[0] == 0x243F6A88, hex(words[0])
assert words[17] == 0x8979FB1B, hex(words[17])
assert words[18] == 0xD1310BA6, hex(words[18])
assert words[-1] == 0x3AC372E6, hex(words[-1])

print("# Generated by tools/gen_blowfish_pi.py: Blowfish's initial state, the hex digits of pi's fractional part.")
print("# P-array: words 0..17. S-boxes: S[i][j] is word 18 + 256 * i + j.\n")
print(f"comptime BLOWFISH_WORDS = {WORDS}\n")
print(f"comptime BLOWFISH_PI = SIMD[DType.uint32, {2048}](")
padded = words + [0] * (2048 - WORDS)  # SIMD widths are powers of two
for i in range(0, len(padded), 8):
    print("    " + ", ".join(f"0x{w:08X}" for w in padded[i:i + 8]) + ",")
print(")")
