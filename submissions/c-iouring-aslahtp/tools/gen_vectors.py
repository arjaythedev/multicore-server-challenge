#!/usr/bin/env python3
"""Writes tests/vectors.h: expected outputs for the unit tests, computed with Python's hashlib, hmac and the
`bcrypt` package (pip install bcrypt), so the C code is checked against independent implementations.

    python3 tools/gen_vectors.py > tests/vectors.h
"""
import base64, hashlib, hmac, json, bcrypt


def c_str(b: bytes) -> str:
    out = []
    for x in b:
        c = chr(x)
        if c in '"\\':
            out.append("\\" + c)
        elif 0x20 <= x < 0x7f and c != '?':
            out.append(c)
        else:
            out.append(f'\\x{x:02x}""')
    return '"' + "".join(out) + '"'


def msg(n: int) -> bytes:
    return bytes((i * 7 + 3) & 0xFF for i in range(n))


print("/* Generated by tools/gen_vectors.py. Do not edit. */")
print("#pragma once\n")

print("struct sha_vec { size_t len; const char *hex; };")
print("static const struct sha_vec sha_vecs[] = {")
for n in [0, 1, 3, 55, 56, 63, 64, 65, 119, 120, 1000]:
    print(f'    {{{n}, "{hashlib.sha256(msg(n)).hexdigest()}"}},')
print("};\n")

print("struct hmac_vec { size_t klen, mlen; const char *hex; };")
print("static const struct hmac_vec hmac_vecs[] = {")
for kl, ml in [(4, 28), (32, 0), (64, 50), (65, 50), (100, 200)]:
    print(f'    {{{kl}, {ml}, "{hmac.new(msg(kl)[::-1], msg(ml), hashlib.sha256).hexdigest()}"}},')
print("};\n")

salt = base64.b64decode("W22ZaJ0SNY7soEsUEjb6gQ==")
print(f'static const char pbkdf2_hex[] = "{hashlib.pbkdf2_hmac("sha256", b"pencil", salt, 4096).hex()}";\n')

print("struct bcrypt_vec { const char *pw; size_t pwlen; const char *hash; };")
print("static const struct bcrypt_vec bcrypt_vecs[] = {")
pws = [b"", b"a", b"password123", b"U*U", "p\u00e4ssw\u00f6rd \u2603".encode(), b"x" * 71, b"0123456789" * 7 + b"ab"]
salts = [b"$2b$04$" + s for s in [b"abcdefghijklmnopqrstuu", b"CCCCCCCCCCCCCCCCCCCCC.", b"......................",
                                   b"999999999999999999999e", b"ZSfEoPvlcsj2XfvsSeK25e", b"/./././././././././.O"[:21].ljust(21, b"/") + b"O",
                                   b"XXXXXXXXXXXXXXXXXXXXXO"]]
for pw, s in zip(pws, salts):
    s = s[:29]
    print(f"    {{{c_str(pw)}, {len(pw)}, \"{bcrypt.hashpw(pw, s).decode()}\"}},")
print('    {"password123", 11, "$2a$10$ZSfEoPvlcsj2XfvsSeK25em4NZ9Jm7ntGqXuLgQfHEeZPYB8899wq"},  /* the seed\'s hash */')
print("};\n")

# JWTs signed with the secret below, checked at time NOW.
SECRET, NOW, UID = b"multicore-server-challenge", 1_800_000_000, 4242


def b64(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def tok(header, claims, secret=SECRET, raw_payload=None) -> str:
    h = b64(json.dumps(header, separators=(",", ":")).encode()) if not isinstance(header, bytes) else b64(header)
    p = b64(raw_payload if raw_payload is not None else json.dumps(claims, separators=(",", ":")).encode())
    sig = b64(hmac.new(secret, f"{h}.{p}".encode(), hashlib.sha256).digest())
    return f"{h}.{p}.{sig}"


H = {"alg": "HS256", "typ": "JWT"}
good = {"sub": str(UID), "iat": NOW - 10, "exp": NOW + 100}
cases = [
    ("valid", tok(H, good), UID),
    ("valid-no-typ", tok({"alg": "HS256"}, good), UID),
    ("valid-float-exp", tok(H, {**good, "exp": NOW + 0.5}), UID),
    ("valid-leading-zero-sub", tok(H, {**good, "sub": "0042"}), 42),
    ("valid-nbf-past", tok(H, {**good, "nbf": NOW - 1}), UID),
    ("valid-aud-list", tok(H, {**good, "aud": ["a", "b"]}), UID),
    ("valid-extra-claims", tok(H, {**good, "role": {"admin": True}}), UID),
    ("wrong-secret", tok(H, good, SECRET + b"-wrong"), 0),
    ("alg-none", b64(b'{"alg":"none","typ":"JWT"}') + "." + b64(json.dumps(good).encode()) + ".", 0),
    ("alg-hs512-signed-hs256", tok({"alg": "HS512"}, good), 0),
    ("expired", tok(H, {**good, "exp": NOW - 1}), 0),
    ("exp-equals-now", tok(H, {**good, "exp": NOW}), 0),
    ("no-exp", tok(H, {"sub": str(UID), "iat": NOW}), 0),
    ("exp-string", tok(H, {**good, "exp": str(NOW + 100)}), 0),
    ("exp-null", tok(H, {**good, "exp": None}), 0),
    ("nbf-future", tok(H, {**good, "nbf": NOW + 5}), 0),
    ("iat-string", tok(H, {**good, "iat": "x"}), 0),
    ("numeric-sub", tok(H, {**good, "sub": UID}), 0),
    ("non-numeric-sub", tok(H, {**good, "sub": "abc"}), 0),
    ("signed-sub", tok(H, {**good, "sub": "+42"}), 0),
    ("zero-sub", tok(H, {**good, "sub": "0"}), 0),
    ("huge-sub", tok(H, {**good, "sub": "9223372036854775808"}), 0),
    ("no-sub", tok(H, {"iat": NOW, "exp": NOW + 100}), 0),
    ("aud-number", tok(H, {**good, "aud": 5}), 0),
    ("payload-array", tok(H, None, raw_payload=b"[1,2]"), 0),
    ("payload-not-json", tok(H, None, raw_payload=b"{oops"), 0),
    ("two-segments", tok(H, good).rsplit(".", 1)[0], 0),
    ("four-segments", tok(H, good) + ".x", 0),
    ("garbage", "not.a.jwt", 0),
    ("padded-signature", tok(H, good) + "=", 0),
]
print(f"#define JWT_SECRET_VEC \"{SECRET.decode()}\"")
print(f"#define JWT_NOW_VEC {NOW}")
print("struct jwt_vec { const char *name, *tok; int64_t uid; };")
print("static const struct jwt_vec jwt_vecs[] = {")
for name, t, uid in cases:
    print(f'    {{"{name}", "{t}", {uid}}},')
print("};")

# SCRAM-SHA-256 as Postgres runs it (RFC 5802/7677 with an empty username), with a fixed client nonce.
nonce_random = bytes(range(18))
cnonce = base64.b64encode(nonce_random).decode()
snonce = cnonce + "SRVnonce+/x"
scram_salt = bytes(range(100, 116))
iters = 4096
password = b"conduit"
server_first = f"r={snonce},s={base64.b64encode(scram_salt).decode()},i={iters}"
cfb = f"n=,r={cnonce}"
final_wo_proof = f"c=biws,r={snonce}"
auth_msg = f"{cfb},{server_first},{final_wo_proof}".encode()
salted = hashlib.pbkdf2_hmac("sha256", password, scram_salt, iters)
ck = hmac.new(salted, b"Client Key", hashlib.sha256).digest()
sk = hmac.new(salted, b"Server Key", hashlib.sha256).digest()
csig = hmac.new(hashlib.sha256(ck).digest(), auth_msg, hashlib.sha256).digest()
proof = bytes(a ^ b for a, b in zip(ck, csig))
ssig = hmac.new(sk, auth_msg, hashlib.sha256).digest()
print()
print(f'#define SCRAM_PASSWORD "{password.decode()}"')
print(f'#define SCRAM_CLIENT_FIRST "n,,{cfb}"')
print(f'#define SCRAM_SERVER_FIRST "{server_first}"')
print(f'#define SCRAM_CLIENT_FINAL "{final_wo_proof},p={base64.b64encode(proof).decode()}"')
print(f'#define SCRAM_SERVER_FINAL "v={base64.b64encode(ssig).decode()}"')
