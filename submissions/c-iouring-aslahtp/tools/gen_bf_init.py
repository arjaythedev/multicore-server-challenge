#!/usr/bin/env python3
"""Writes src/bf_init.h: Blowfish's initial P-array and S-boxes, which are the hex digits of pi's fractional part.

    python3 tools/gen_bf_init.py > src/bf_init.h

pi is computed with Machin's formula in integer arithmetic, so the output depends on nothing but this script.
"""
import sys

WORDS = 18 + 4 * 256          # P-array + 4 S-boxes
BITS = WORDS * 32 + 64         # guard bits so the last word is exact


def arctan_inv(x: int, one: int) -> int:
    """arctan(1/x) * one, by its Taylor series."""
    total = term = one // x
    x2, n, sign = x * x, 3, -1
    while term:
        term //= x2
        total += sign * (term // n)
        sign, n = -sign, n + 2
    return total


one = 1 << BITS
pi = 16 * arctan_inv(5, one) - 4 * arctan_inv(239, one)
frac = pi - 3 * one                                  # fractional part, scaled by 2^BITS
words = [(frac >> (BITS - 32 * (i + 1))) & 0xFFFFFFFF for i in range(WORDS)]

assert words[0] == 0x243F6A88 and words[17] == 0x8979FB1B, "P-array check"
assert words[18] == 0xD1310BA6 and words[-1] == 0x3AC372E6, "S-box check"

out = sys.stdout
out.write("/* Generated by tools/gen_bf_init.py: the hex digits of pi after the point. Do not edit. */\n")
out.write("#pragma once\n#include <stdint.h>\n\n")
out.write("static const uint32_t bf_init_P[18] = {\n")
for i in range(0, 18, 6):
    out.write("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 6]) + ",\n")
out.write("};\n\nstatic const uint32_t bf_init_S[4][256] = {\n")
for b in range(4):
    out.write("  {\n")
    box = words[18 + 256 * b: 18 + 256 * (b + 1)]
    for i in range(0, 256, 6):
        out.write("    " + ", ".join(f"0x{w:08x}" for w in box[i:i + 6]) + ",\n")
    out.write("  },\n")
out.write("};\n")
