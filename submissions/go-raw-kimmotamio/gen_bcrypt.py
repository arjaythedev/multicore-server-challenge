# gen_bcrypt.py: generates bcrypt_lanes.go, the N-lane interleaved Blowfish key schedule used by bcrypt.go.
# Each lane is an independent bcrypt computation; running N of them in lockstep lets the CPU overlap
# the dependent S-box loads of one lane with the arithmetic of the others.
import sys
LANES=[1,2,3,4]
out=['// Code generated by gen_bcrypt.py; DO NOT EDIT.','','package main','']
for N in LANES:
    L=range(N)
    def enc(indent):
        # one Blowfish encryption of (l[k], r[k]) for every lane k, interleaved per round
        s=[]
        for k in L: s.append(f'{indent}l{k} ^= c{k}.p[0]')
        for rnd in range(1,17):
            src,dst=('l','r') if rnd%2==1 else ('r','l')
            for k in L:
                s.append(f'{indent}{dst}{k} ^= ((c{k}.s0[byte({src}{k}>>24)]+c{k}.s1[byte({src}{k}>>16)])^c{k}.s2[byte({src}{k}>>8)])+c{k}.s3[byte({src}{k})]^c{k}.p[{rnd}]')
        for k in L: s.append(f'{indent}r{k} ^= c{k}.p[17]')
        for k in L: s.append(f'{indent}l{k}, r{k} = r{k}, l{k}')
        return '\n'.join(s)
    out.append(f'// expandKey{N} runs blowfish.ExpandKey on {N} ciphers at once; kw holds each lane\'s 18 key words.')
    out.append(f'func expandKey{N}(cs *[{N}]*bfState, kw *[{N}][18]uint32) {{')
    for k in L: out.append(f'\tc{k} := cs[{k}]')
    out.append('\tfor i := 0; i < 18; i++ {')
    for k in L: out.append(f'\t\tc{k}.p[i] ^= kw[{k}][i]')
    out.append('\t}')
    out.append('\tvar ' + ', '.join(f'l{k}, r{k}' for k in L) + ' uint32')
    out.append('\tfor i := 0; i < 18; i += 2 {')
    out.append(enc('\t\t'))
    for k in L: out.append(f'\t\tc{k}.p[i], c{k}.p[i+1] = l{k}, r{k}')
    out.append('\t}')
    for box in ['s0','s1','s2','s3']:
        out.append('\tfor i := 0; i < 256; i += 2 {')
        out.append(enc('\t\t'))
        for k in L: out.append(f'\t\tc{k}.{box}[i], c{k}.{box}[i+1] = l{k}, r{k}')
        out.append('\t}')
    out.append('}')
    out.append('')
open('bcrypt_lanes.go','w').write('\n'.join(out))
