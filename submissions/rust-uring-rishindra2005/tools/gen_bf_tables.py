#!/usr/bin/env python3
"""Generate Blowfish P-array and S-boxes from hexadecimal digits of pi."""

import os
import sys

def generate_pi_words():
    guard = 256
    total_bits = 1042 * 32
    N = total_bits + guard
    scale = 1 << N

    def arccot(x, s):
        total = 0
        num = s // x
        k = 1
        x_sq = x * x
        sign = 1
        while num > 0:
            term = num // k
            if sign > 0:
                total += term
            else:
                total -= term
            sign = -sign
            num = num // x_sq
            k += 2
        return total

    pi_scaled = 16 * arccot(5, scale) - 4 * arccot(239, scale)
    frac = pi_scaled & ((1 << N) - 1)
    frac >>= guard

    words = []
    for _ in range(1042):
        w = (frac >> (total_bits - 32)) & 0xffffffff
        words.append(w)
        frac = (frac << 32) & ((1 << total_bits) - 1)
    return words

def format_rust(words):
    p_words = words[:18]
    s_words = words[18:]

    lines = []
    lines.append("//! Blowfish initial P-array and S-boxes: hexadecimal digits of pi (generated by gen_bf_tables.py).")
    lines.append("")
    lines.append("pub const PI_P: [u32; 18] = [")
    for i in range(0, 18, 4):
        chunk = p_words[i:i+4]
        formatted = ", ".join(f"0x{w:08x}" for w in chunk)
        lines.append(f"    {formatted},")
    lines.append("];")
    lines.append("")
    lines.append("pub const PI_S: [[u32; 256]; 4] = [")
    for box_idx in range(4):
        lines.append("    [")
        box = s_words[box_idx * 256 : (box_idx + 1) * 256]
        for i in range(0, 256, 4):
            chunk = box[i:i+4]
            formatted = ", ".join(f"0x{w:08x}" for w in chunk)
            lines.append(f"        {formatted},")
        lines.append("    ],")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)

def main():
    target = sys.argv[1] if len(sys.argv) > 1 else "/home/rishi/Desktop/tmp/swarm/ws/loadgen/sub/src/sec/bf_tables.rs"
    os.makedirs(os.path.dirname(os.path.abspath(target)), exist_ok=True)
    words = generate_pi_words()
    content = format_rust(words)
    with open(target, "w") as f:
        f.write(content)
    print(f"Wrote {len(words)} pi words to {target}")

if __name__ == "__main__":
    main()
