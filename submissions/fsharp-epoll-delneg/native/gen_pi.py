# Writes native/bf_init.h: Blowfish's initial P-array and S-boxes, which are the fractional hex digits of pi
# (Schneier 1993). Computed here with Machin's formula in integer arithmetic, no table copied.
import sys
WORDS = 18 + 4 * 256
BITS = WORDS * 32 + 64
def arctan_inv(x, one):
    # arctan(1/x) * one
    total = term = one // x
    x2, n, sign = x * x, 1, 1
    while term:
        term //= x2
        n += 2
        sign = -sign
        total += sign * (term // n)
    return total
one = 1 << (BITS + 32)
pi = 4 * (4 * arctan_inv(5, one) - arctan_inv(239, one))
frac = pi - (3 * one)                 # fractional part, scaled by 2^(BITS+32)
frac >>= 32 + 64                      # drop guard bits: now WORDS*32 bits
words = [(frac >> (32 * (WORDS - 1 - i))) & 0xFFFFFFFF for i in range(WORDS)]
assert words[0] == 0x243F6A88 and words[1] == 0x85A308D3, hex(words[0])
out = ["/* Generated by gen_pi.py: the first %d 32-bit words of pi's fractional hex digits. */" % WORDS,
       "static const unsigned int BF_INIT[%d] = {" % WORDS]
for i in range(0, WORDS, 6):
    out.append("  " + ", ".join("0x%08x" % w for w in words[i:i + 6]) + ",")
out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("last word %08x" % words[-1])
