#!/usr/bin/env python3
# Generates src/bcrypt_expand0.c, top-level assembly that dune builds as a C stub. The technique follows zig-iouring-nick-potts's asm_gen.zig: hand-scheduled Blowfish
# with one base register, every lane's halves in registers, and BEXTR/RORX byte extraction.
import sys
WORDS=18+1024; STRIDE=WORDS*4; ENC=WORDS//2
H=[("ebx","ebp"),("r8d","r9d"),("r10d","r11d"),("r12d","r13d"),("r14d","r15d")]
LOW=[("bl","bpl"),("r8b","r9b"),("r10b","r11b"),("r12b","r13b"),("r14b","r15b")]
out=[]
def half(u,hx,r):
    base=u*STRIDE; s=base+72; x=H[u][hx]; y=H[u][1-hx]
    out.append(f"  xor {y}, dword ptr [rdi + {base+4*r}]")
    out.append(f"  rorx eax, {x}, 16")
    out.append("  movzx esi, ah")
    out.append(f"  mov edx, dword ptr [rdi + rsi*4 + {s}]")
    out.append("  movzx esi, al")
    out.append(f"  add edx, dword ptr [rdi + rsi*4 + {s+1024}]")
    out.append(f"  bextr esi, {x}, ecx")
    out.append(f"  xor edx, dword ptr [rdi + rsi*4 + {s+2048}]")
    out.append(f"  movzx esi, {LOW[u][hx]}")
    out.append(f"  add edx, dword ptr [rdi + rsi*4 + {s+3072}]")
    out.append(f"  xor {y}, edx")
def fn(n):
    name=f"conduit_expand0_{n}"
    out.extend([f"  .globl {name}",f"  .type {name}, @function","  .p2align 6",f"{name}:"])
    for r in ["rbx","rbp","r12","r13","r14","r15"]: out.append(f"  push {r}")
    out.append("  sub rsp, 8")
    out.append("  mov ecx, 0x0808")
    out.append("  mov qword ptr [rsp], 0")
    for u in range(n):
        out.append(f"  xor {H[u][0]}, {H[u][0]}"); out.append(f"  xor {H[u][1]}, {H[u][1]}")
    out.append("  .p2align 4"); out.append(f".Lenc_{n}:")
    for u in range(n): out.append(f"  xor {H[u][0]}, dword ptr [rdi + {u*STRIDE}]")
    for r in range(1,17,2):
        for u in range(n): half(u,0,r)
        for u in range(n): half(u,1,r+1)
    out.append("  mov rsi, qword ptr [rsp]")
    for u in range(n):
        b=u*STRIDE; l,rr=H[u]
        out.append(f"  xor {rr}, dword ptr [rdi + {b+68}]")
        out.append(f"  mov dword ptr [rdi + rsi*8 + {b}], {rr}")
        out.append(f"  mov dword ptr [rdi + rsi*8 + {b+4}], {l}")
        out.append(f"  mov edx, {l}"); out.append(f"  mov {l}, {rr}"); out.append(f"  mov {rr}, edx")
    out.append("  add rsi, 1"); out.append("  mov qword ptr [rsp], rsi"); out.append(f"  cmp rsi, {ENC}"); out.append(f"  jb .Lenc_{n}")
    out.append("  add rsp, 8")
    for r in ["r15","r14","r13","r12","rbp","rbx"]: out.append(f"  pop {r}")
    out.append("  ret"); out.append(f"  .size {name}, .-{name}")
out.append("  .intel_syntax noprefix"); out.append("  .text")
for n in range(1,6): fn(n)
out.append("  .att_syntax"); out.append('  .section .note.GNU-stack,"",@progbits'); out.append("  .text")
c=["/* Generated by dev/gen_expand0.py: one bcrypt cost-loop expansion over 1 to 5 lanes. */","#if defined(__x86_64__)","__asm__("]
c+=['"'+l.replace('"','\\"')+'\\n"' for l in out]
c+=[");","#endif"]
open(sys.argv[1],'w').write("\n".join(c)+"\n")
