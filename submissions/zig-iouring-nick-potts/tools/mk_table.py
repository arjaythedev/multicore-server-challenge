"""Builds pz's fixed dynamic Huffman table, src/pz_table_anchor.zig, from symbol counts.

  python3 -I tools/mk_table.py tools/counts.txt     (from the submission folder) rewrites src/pz_table_anchor.zig

tools/counts.txt is one line: "all", then 286 lit/len and 30 distance symbol counts, the totals of pz's own parse
(8 bytes hashed at an anchor) over 2,000 response bodies of 3+ TCP segments captured from a load run against the
seed. It holds only those 316 totals, no body. Every lit/len symbol 0..285 gets a code (count floored at 1), so any
input encodes. The literal codes are length-limited to 11 bits (anchor mode codes literals in pairs from a 22-bit
table entry), distance codes to 15, by package-merge, so they are complete, and the header is checked with zlib.
"""
import os, sys, zlib

CL_ORDER = [16, 17, 18, 0, 8, 7, 9, 6, 10, 5, 11, 4, 12, 3, 13, 2, 14, 1, 15]


def package_merge(freqs, limit):
    syms = [(f, (i,)) for i, f in enumerate(freqs) if f > 0]
    lens = [0] * len(freqs)
    if len(syms) == 1:
        lens[syms[0][1][0]] = 1
        return lens
    orig = sorted(syms)
    cur = list(orig)
    for _ in range(limit - 1):
        pk = [(cur[i][0] + cur[i + 1][0], cur[i][1] + cur[i + 1][1]) for i in range(0, len(cur) - 1, 2)]
        cur = sorted(orig + pk, key=lambda x: x[0])
    for _, s in cur[: 2 * len(syms) - 2]:
        for i in s:
            lens[i] += 1
    assert sum(2.0 ** -l for l in lens if l) == 1.0
    return lens


def canon(lens):
    """Bit-reversed canonical codes (deflate writes Huffman codes MSB first into an LSB-first stream)."""
    maxl = max(lens)
    bl = [0] * (maxl + 1)
    for l in lens:
        if l:
            bl[l] += 1
    code, nxt = 0, [0] * (maxl + 2)
    for b in range(1, maxl + 1):
        code = (code + bl[b - 1]) << 1
        nxt[b] = code
    out = []
    for l in lens:
        if not l:
            out.append(0)
            continue
        c = nxt[l]
        nxt[l] += 1
        out.append(int(format(c, f"0{l}b")[::-1], 2))
    return out


def rle(lens):
    out, i, n = [], 0, len(lens)
    while i < n:
        l = lens[i]
        run = 1
        while i + run < n and lens[i + run] == l:
            run += 1
        if l == 0 and run >= 3:
            while run >= 11:
                r = min(run, 138)
                out.append((18, r - 11, 7)); i += r; run -= r
            if run >= 3:
                out.append((17, run - 3, 3)); i += run; run = 0
            for _ in range(run):
                out.append((0, 0, 0)); i += 1
        else:
            out.append((l, 0, 0)); i += 1; run -= 1
            if l:
                while run >= 3:
                    r = min(run, 6)
                    out.append((16, r - 3, 2)); i += r; run -= r
            for _ in range(run):
                out.append((l, 0, 0)); i += 1
    return out


class Bits:
    def __init__(self):
        self.v, self.n = 0, 0

    def put(self, val, n):
        self.v |= val << self.n
        self.n += n

    def bytes(self):
        return self.v.to_bytes((self.n + 7) // 8 + 8, "little")


def build(lit, dist, out):
    lit = [max(1, f) for f in lit]
    llens = package_merge(lit, 11)
    dlens = package_merge([max(1, f) for f in dist], 15)
    allens = llens + dlens
    sy = rle(allens)
    clf = [0] * 19
    for s, _, _ in sy:
        clf[s] += 1
    cll = package_merge(clf, 7)
    clc = canon(cll)
    ncl = 19
    while ncl > 4 and cll[CL_ORDER[ncl - 1]] == 0:
        ncl -= 1
    h = Bits()
    h.put(len(llens) - 257, 5)
    h.put(len(dlens) - 1, 5)
    h.put(ncl - 4, 4)
    for k in range(ncl):
        h.put(cll[CL_ORDER[k]], 3)
    for s, e, eb in sy:
        h.put(clc[s], cll[s])
        if eb:
            h.put(e, eb)
    lc, dc = canon(llens), canon(dlens)
    # check: BFINAL=1, BTYPE=10, header, EOB must inflate to b""
    t = Bits()
    t.put(1 | 2 << 1, 3)
    t.v |= h.v << 3
    t.n += h.n
    t.put(lc[256], llens[256])
    assert zlib.decompress(t.bytes()[: (t.n + 7) // 8], -15) == b""
    hb = h.bytes()
    hlen = (h.n + 7) // 8
    with open(out, "w") as f:
        f.write(f"//! Generated by tools/mk_table.py: pz's preset dynamic Huffman table (anchor mode), header {h.n} bits.\n")
        f.write("pub const lit_code = [286]u16{ " + ", ".join(map(str, lc)) + " };\n")
        f.write("pub const lit_len = [286]u8{ " + ", ".join(map(str, llens)) + " };\n")
        f.write("pub const dist_code = [30]u16{ " + ", ".join(map(str, dc)) + " };\n")
        f.write("pub const dist_len = [30]u8{ " + ", ".join(map(str, dlens)) + " };\n")
        f.write(f"/// The block header after BFINAL/BTYPE (HLIT, HDIST, HCLEN, code lengths), LSB first, {hlen} bytes + 8 of zeros.\n")
        f.write(f"pub const hdr = [{hlen + 8}]u8{{ " + ", ".join(map(str, hb[: hlen + 8])) + " };\n")
        f.write(f"pub const hdr_bits = {h.n};\n")
    print(f"{out}: header {h.n} bits, literal lengths {min(llens[:256])}..{max(llens[:256])}")


def main():
    p = open(sys.argv[1]).read().split()
    assert p[0] == "all" and len(p) == 317
    v = list(map(int, p[1:]))
    build(v[:286], v[286:], os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "pz_table_anchor.zig"))


main()
