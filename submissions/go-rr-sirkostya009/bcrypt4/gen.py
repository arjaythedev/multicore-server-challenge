# Writes fill_gen.go: Blowfish's key-schedule fill for four interleaved lanes.
# The lanes share no data, so the CPU overlaps their S-box loads.
#   python3 gen.py
L = 4


def rnd(k, src, dst, pi):
    return (f"\t\t{dst}{k} ^= ((c{k}.s0[byte({src}{k}>>24)] + c{k}.s1[byte({src}{k}>>16)]) ^ "
            f"c{k}.s2[byte({src}{k}>>8)]) + c{k}.s3[byte({src}{k})] ^ c{k}.p[{pi}]\n")


def enc():
    out = "".join(f"\t\tl{k} ^= c{k}.p[0]\n" for k in range(L))
    for i in range(1, 17):
        src, dst = ("l", "r") if i % 2 == 1 else ("r", "l")
        out += "".join(rnd(k, src, dst, i) for k in range(L))
    out += "".join(f"\t\tr{k} ^= c{k}.p[17]\n" for k in range(L))
    out += "".join(f"\t\tl{k}, r{k} = r{k}, l{k}\n" for k in range(L))
    return out


def fill(name, salted):
    s = f"func {name}(c *[{L}]state" + (f", sw *[{L}][4]uint32" if salted else "") + ") {\n"
    s += "\t" + ", ".join(f"c{k}" for k in range(L)) + " := " + ", ".join(f"&c[{k}]" for k in range(L)) + "\n"
    s += "\t" + ", ".join(f"f{k}" for k in range(L)) + " := " + ", ".join(f"c{k}.flat()" for k in range(L)) + "\n"
    s += "\tvar " + ", ".join(f"l{k}, r{k}" for k in range(L)) + " uint32\n"
    s += "\tfor i := 0; i < stateWords; i += 2 {\n"
    if salted:
        s += "\t\th := i & 2\n"
        s += "".join(f"\t\tl{k} ^= sw[{k}][h]\n\t\tr{k} ^= sw[{k}][h+1]\n" for k in range(L))
    s += enc()
    s += "".join(f"\t\tf{k}[i], f{k}[i+1] = l{k}, r{k}\n" for k in range(L))
    s += "\t}\n}\n"
    return s


src = "// Code generated by gen.py. DO NOT EDIT.\n\npackage bcrypt4\n\n"
src += fill("fill4", False) + "\n" + fill("fillSalted4", True)
open("fill_gen.go", "w").write(src)
