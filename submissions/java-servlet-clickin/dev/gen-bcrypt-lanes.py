#!/usr/bin/env python3
"""Writes src/challenge/BCryptLanes.java: bcrypt's Blowfish work for K hashes at once, K = 1..MAX.

One bcrypt is a single chain of dependent S-box loads, so a core running it alone mostly waits on L1. K independent
hashes with their rounds interleaved, each lane in its own locals, let the core overlap K chains. Java can't express
that for a variable K without spilling the lanes to arrays, so this writes one straight-line kernel per K. Which K is
fastest depends on the core (registers, load ports), so BCryptLanes.fastest() times them at startup.

    python3 dev/gen-bcrypt-lanes.py > src/challenge/BCryptLanes.java && bash dev/format.sh
"""
import sys

MAX = 6


def f(k, x):
    s = f"s{k}"
    return f"(({s}[{x} >>> 24] + {s}[256 | {x} >>> 16 & 255]) ^ {s}[512 | {x} >>> 8 & 255]) + {s}[768 | {x} & 255]"


def rounds(K, ind):
    out = [f"{ind}l{k} ^= p{k}[0];" for k in range(K)]
    for i in range(1, 17, 2):
        out += [f"{ind}r{k} ^= {f(k, f'l{k}')} ^ p{k}[{i}];" for k in range(K)]
        out += [f"{ind}l{k} ^= {f(k, f'r{k}')} ^ p{k}[{i + 1}];" for k in range(K)]
    for k in range(K):
        out.append(f"{ind}r{k} ^= p{k}[17];")
    return out


def locals_(K, ind):
    out = []
    for k in range(K):
        out.append(f"{ind}int[] p{k} = p[{k}];")
        out.append(f"{ind}int[] s{k} = s[{k}];")
    return out


def kernel(K):
    L = []
    for salted in (False, True):
        name = "expandSalted" if salted else "expand"
        doc = ("p ^= key, then re-key P and S with the 4 salt words xored into each block (the setup expansion)" if salted
               else "p ^= key (18 words), then re-key P and S from a zero block (the cost loop's expansion)")
        L.append(f"    /** {doc}. */")
        L.append(f"    static void {name}{K}(int[][] p, int[][] s, int[][] key{', int[][] salt' if salted else ''}) {{")
        L += locals_(K, "        ")
        for k in range(K):
            L.append(f"        xor(p{k}, key[{k}]);")
            if salted:
                L.append(f"        int[] w{k} = salt[{k}];")
        for k in range(K):
            L.append(f"        int l{k} = 0;")
            L.append(f"        int r{k} = 0;")
        # one loop over P then S: two copies of a 6-lane body would pass HugeMethodLimit and never compile
        L.append("        for (int i = 0; i < 18 + 1024; i += 2) {")
        if salted:
            # salt words alternate 0,1 / 2,3 per block, continuing from P into S
            for k in range(K):
                L.append(f"            l{k} ^= w{k}[i & 2];")
                L.append(f"            r{k} ^= w{k}[(i & 2) + 1];")
        L += rounds(K, "            ")
        L.append("            if (i < 18) {")
        for k in range(K):
            L.append(f"                p{k}[i] = r{k};")
            L.append(f"                p{k}[i + 1] = l{k};")
        L.append("            } else {")
        for k in range(K):
            L.append(f"                s{k}[i - 18] = r{k};")
            L.append(f"                s{k}[i - 17] = l{k};")
        L.append("            }")
        for k in range(K):
            L.append(f"            int t{k} = l{k};")
            L.append(f"            l{k} = r{k};")
            L.append(f"            r{k} = t{k};")
        L.append("        }")
        L.append("    }")
        L.append("")
    L.append("    /** Encrypts each lane's 6-word text in place 64 times (the output step). */")
    L.append(f"    static void encrypt{K}(int[][] p, int[][] s, int[][] text) {{")
    L += locals_(K, "        ")
    L.append("        for (int n = 0; n < 64; n++) {")
    L.append("            for (int j = 0; j < 6; j += 2) {")
    for k in range(K):
        L.append(f"                int l{k} = text[{k}][j];")
        L.append(f"                int r{k} = text[{k}][j + 1];")
    L += rounds(K, "                ")
    for k in range(K):
        L.append(f"                text[{k}][j] = r{k};")
        L.append(f"                text[{k}][j + 1] = l{k};")
    L.append("            }")
    L.append("        }")
    L.append("    }")
    L.append("")
    return L


def dispatch(name, params, args):
    L = [f"    static void {name}(int lanes, {params}) {{", "        switch (lanes) {"]
    for K in range(1, MAX + 1):
        L.append(f"            case {K} -> {name}{K}({args});")
    L += ["            default -> throw new IllegalArgumentException(\"lanes: \" + lanes);", "        }", "    }", ""]
    return L


def main():
    L = ["// Generated by dev/gen-bcrypt-lanes.py; edit the script, not this file.",
         "package challenge;",
         "",
         "/** bcrypt's Blowfish work for 1..MAX hashes at once, their rounds interleaved so the core overlaps the S-box loads. */",
         "final class BCryptLanes {",
         f"    static final int MAX = {MAX};",
         "",
         "    private BCryptLanes() {",
         "    }",
         "",
         "    private static void xor(int[] p, int[] key) {",
         "        for (int i = 0; i < 18; i++) {",
         "            p[i] ^= key[i];",
         "        }",
         "    }",
         ""]
    for K in range(1, MAX + 1):
        L += kernel(K)
    L += dispatch("expand", "int[][] p, int[][] s, int[][] key", "p, s, key")
    L += dispatch("expandSalted", "int[][] p, int[][] s, int[][] key, int[][] salt", "p, s, key, salt")
    L += dispatch("encrypt", "int[][] p, int[][] s, int[][] text", "p, s, text")
    L.append("}")
    sys.stdout.write("\n".join(L) + "\n")


main()
