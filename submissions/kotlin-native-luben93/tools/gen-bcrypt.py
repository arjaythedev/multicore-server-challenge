#!/usr/bin/env python3
"""Generates src/commonMain/kotlin/conduit/crypto/BcryptLanes.kt: Blowfish's initial state and bcrypt's EksBlowfish
rounds for 1..4 interleaved lanes, fully unrolled (16 rounds per block; lanes interleaved per half-round so the
out-of-order core overlaps the lanes' dependent S-box loads). Self-contained: the initial state is the hex
expansion of pi, computed here.

Layout: one IntArray(1042) per lane (P = [0, 18), S0..S3 = [18 + 256 * b, ...)), allocated inside the generated
function so the compiler knows its length and every S-box index is provably in range. Measured at cost 10
(ms per hash for 1/2/3/4 lanes): JVM 48.5/25.4/23.8/22.9, Kotlin/Native -opt 55.1/30.3/21.6/18.5. A single
IntArray holding all lanes measured the same on the JVM and worse on Native (55.4/30.8/26.8/23.0).

Usage: python3 tools/gen-bcrypt.py [out.kt]
"""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    here, "..", "src", "commonMain", "kotlin", "conduit", "crypto", "BcryptLanes.kt")

# ---- pi in hex: floor(pi * 16^D) by Machin's formula, pi = 16 atan(1/5) - 4 atan(1/239)
WORDS = 18 + 1024
D = WORDS * 8 + 16  # hex digits + guard digits


def atan_inv(x, one):
    total = term = one // x
    x2 = x * x
    n, sign = 1, -1
    while term:
        term //= x2
        total += sign * (term // (2 * n + 1))
        sign, n = -sign, n + 1
    return total


one = 1 << (4 * D)
pi = 16 * atan_inv(5, one) - 4 * atan_inv(239, one)
hexpi = format(pi, "x")
assert hexpi[0] == "3"
words = [int(hexpi[1 + 8 * i:9 + 8 * i], 16) for i in range(WORDS)]
P, S = words[:18], words[18:]
# well-known anchors of Blowfish's tables
assert P[0] == 0x243F6A88 and P[17] == 0x8979FB1B
assert S[0] == 0xD1310BA6 and S[255] == 0x6E85076A and S[256] == 0x4B7A70E9
assert S[512] == 0xE93D5A68 and S[768] == 0x3A39CE37 and S[1023] == 0x3AC372E6

W = 1042
LANE = "abcd"

out = []
w = out.append
w("// GENERATED by tools/gen-bcrypt.py; do not edit by hand.")
w('@file:Suppress("NAME_SHADOWING", "DuplicatedCode")')
w("")
w("package conduit.crypto")
w("")
w("/** Blowfish's initial state, P (18 words) then S0..S3 (4 x 256): the fractional hex digits of pi. */")
w("internal val BF_INIT: IntArray = bfWords(")
hexall = "".join("%08x" % v for v in words)
for i in range(0, len(hexall), 112):
    w(f'    "{hexall[i:i + 112]}" +')
out[-1] = out[-1][:-2]
w(")")
w("")
w("private fun bfWords(h: String): IntArray =")
w("    IntArray(h.length / 8) { h.substring(it * 8, it * 8 + 8).toLong(16).toInt() }")
w("")


def F(a, x):
    return (f"((({a}[({x} ushr 24) + 18] + {a}[(({x} ushr 16) and 0xff) + 274]) xor "
            f"{a}[(({x} ushr 8) and 0xff) + 530]) + {a}[({x} and 0xff) + 786])")


def gen(n):
    kp = ", ".join(f"k{k}: IntArray" for k in range(n))
    sp = ", ".join(f"s{k}: IntArray" for k in range(n))
    op = ", ".join(f"o{k}: ByteArray" for k in range(n))
    lanes = "1 lane" if n == 1 else f"{n} interleaved lanes"
    w(f"/** bcrypt, {lanes}: key words k (18), salt words s (4), 2^cost rounds; the 24 raw bytes go to o. */")
    w(f"internal fun eks{n}({kp}, {sp}, cost: Int, {op}) {{")
    for k in range(n):
        a = LANE[k]
        w(f"    val {a} = IntArray({W}); bfSetup({a}, k{k}, s{k}); val t{k} = bfSaltKey(s{k})")
    w("    var rounds = 2L shl cost // 2^cost x (ExpandKey(key), ExpandKey(salt))")
    w("    while (rounds > 0L) {")
    w("        val salt = (rounds and 1L) != 0L")
    for k in range(n):
        w(f"        val x{k} = if (salt) t{k} else k{k}")
    w("        var j = 0")
    w("        while (j < 18) {")
    for k in range(n):
        w(f"            {LANE[k]}[j] = {LANE[k]}[j] xor x{k}[j]")
    w("            j++")
    w("        }")
    w("        " + "; ".join(f"var l{k} = 0; var r{k} = 0" for k in range(n)))
    w("        var i = 0")
    w(f"        while (i < {W}) {{")
    for k in range(n):
        w(f"            l{k} = l{k} xor {LANE[k]}[0]")
    # P[i] is XORed in before F's result arrives (left to right), keeping it off the load chain
    for rnd in range(1, 17, 2):
        for k in range(n):
            w(f"            r{k} = r{k} xor {LANE[k]}[{rnd}] xor {F(LANE[k], f'l{k}')}")
        for k in range(n):
            w(f"            l{k} = l{k} xor {LANE[k]}[{rnd + 1}] xor {F(LANE[k], f'r{k}')}")
    for k in range(n):
        a = LANE[k]
        w(f"            val n{k} = r{k} xor {a}[17]; r{k} = l{k}; l{k} = n{k}; {a}[i] = l{k}; {a}[i + 1] = r{k}")
    w("            i += 2")
    w("        }")
    w("        rounds--")
    w("    }")
    for k in range(n):
        w(f"    bfFinish({LANE[k]}, o{k})")
    w("}")
    w("")


for n in (1, 2, 3, 4):
    gen(n)

with open(out_path, "w") as f:
    f.write("\n".join(out).rstrip("\n") + "\n")
print("wrote", os.path.relpath(out_path), len(out), "lines")
