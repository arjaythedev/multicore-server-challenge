#!/usr/bin/env python3
"""Generate src/bcrypt/tables.rs: the Blowfish initial P-array and S-boxes.

Blowfish seeds its state with the fractional hexadecimal digits of pi: 18 words for the P-array, then 4 * 256
words for the S-boxes (1042 words, 33344 bits). We compute pi with Machin's formula in Python big integers, so
the table is reproducible and not copied from anywhere:

    pi = 16 * atan(1/5) - 4 * atan(1/239)

Usage (from the crate root):  python3 tools/gen_blowfish_tables.py > src/bcrypt/tables.rs
"""

P_WORDS = 18
S_BOXES = 4
S_WORDS = 256
TOTAL_WORDS = P_WORDS + S_BOXES * S_WORDS
GUARD_BITS = 128  # extra precision so rounding errors never reach the bits we keep


def arctan_inv(x: int, one: int) -> int:
    """atan(1/x) scaled by `one`, by the alternating Taylor series."""
    x2 = x * x
    term = one // x
    total = term
    n = 1
    while term:
        term //= x2
        n += 2
        total += -(term // n) if (n // 2) % 2 else term // n
    return total


def pi_fraction_words(count: int) -> list[int]:
    bits = count * 32
    one = 1 << (bits + GUARD_BITS)
    pi = 16 * arctan_inv(5, one) - 4 * arctan_inv(239, one)
    frac = (pi - 3 * one) >> GUARD_BITS  # fractional part of pi, `bits` bits
    return [(frac >> (bits - 32 * (i + 1))) & 0xFFFFFFFF for i in range(count)]


def main() -> None:
    words = pi_fraction_words(TOTAL_WORDS)
    assert words[0] == 0x243F6A88 and words[1] == 0x85A308D3 and words[P_WORDS] == 0xD1310BA6
    print("//! Blowfish initial state: the fractional hex digits of pi.")
    print("//!")
    print("//! GENERATED by `tools/gen_blowfish_tables.py`. Do not edit by hand.")
    print()
    print(f"/// Initial P-array ({P_WORDS} words).")
    print(f"pub const P_INIT: [u32; {P_WORDS}] = [")
    for w in words[:P_WORDS]:
        print(f"    0x{w:08x},")
    print("];")
    print()
    print(f"/// Initial S-boxes ({S_BOXES} boxes of {S_WORDS} words).")
    print(f"pub const S_INIT: [[u32; {S_WORDS}]; {S_BOXES}] = [")
    for b in range(S_BOXES):
        print("    [")
        base = P_WORDS + b * S_WORDS
        for r in range(0, S_WORDS, 4):
            row = ", ".join(f"0x{w:08x}" for w in words[base + r : base + r + 4])
            print(f"        {row},")
        print("    ],")
    print("];")


if __name__ == "__main__":
    main()
