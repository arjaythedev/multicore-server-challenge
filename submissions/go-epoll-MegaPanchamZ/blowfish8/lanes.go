func encBlock(b *bfBox, xl, xr uint32) (uint32, uint32) {
	xl ^= b.p[0]
	for i := 1; i < 17; i += 2 {
		xr ^= (((b.s0[xl>>24] + b.s1[uint8(xl>>16)]) ^ b.s2[uint8(xl>>8)]) + b.s3[uint8(xl)]) ^ b.p[i]
		xl ^= (((b.s0[xr>>24] + b.s1[uint8(xr>>16)]) ^ b.s2[uint8(xr>>8)]) + b.s3[uint8(xr)]) ^ b.p[i+1]
	}
	xr ^= b.p[17]
	return xr, xl
}

