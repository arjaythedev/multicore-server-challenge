#!/usr/bin/env python3
"""Writes the two generated bcrypt files next to this folder:

  BlowfishConstants.g.cs  the Blowfish P-array and S-boxes: the hexadecimal digits of pi, computed here (Machin's formula)
  BcryptLanes.g.cs        the EksBlowfish key-expansion step for 1..MAX_LANES independent hashes run in lockstep

Run it again only if you change the lane code below:  python3 Tools/gen_bcrypt.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
import sys
MAX_LANES = int(os.environ.get('LANES', '4'))
WORDS = 18 + 4 * 256  # P-array + four S-boxes


def pi_words(count):
    """The first `count` 32-bit words of the fractional part of pi (the Blowfish initial state)."""
    bits = count * 32 + 64
    one = 1 << bits

    def arctan_inv(x):
        x2 = x * x
        term = one // x
        total = term
        k = 1
        while term:
            term //= x2
            total += -(term // (2 * k + 1)) if k % 2 else term // (2 * k + 1)
            k += 1
        return total

    pi = 16 * arctan_inv(5) - 4 * arctan_inv(239)
    frac = (pi - 3 * one) >> 64  # drop the guard bits: `count` * 32 bits of fraction are left
    return [(frac >> (32 * (count - 1 - i))) & 0xFFFFFFFF for i in range(count)]


def constants_file(words):
    lines = []
    for i in range(0, len(words), 8):
        lines.append("        " + ", ".join(f"0x{w:08X}" for w in words[i:i + 8]) + ",")
    return f"""// <auto-generated>Tools/gen_bcrypt.py wrote this file; do not edit it by hand.</auto-generated>
namespace Conduit;

internal static class BlowfishConstants
{{
    /// <summary>The initial Blowfish state: 18 P-array words, then four S-boxes of 256 words. They are the hexadecimal digits of pi.</summary>
    internal static ReadOnlySpan<uint> Initial => new uint[]
    {{
{chr(10).join(lines)}
    }};
}}
"""


def f(lane, x):
    s = f"s{lane}"
    return f"(((({s}[{x} >> 24] + {s}[256 + (({x} >> 16) & 0xFF)]) ^ {s}[512 + (({x} >> 8) & 0xFF)]) + {s}[768 + ({x} & 0xFF)]))"


def lanes_file():
    out = ["""// <auto-generated>Tools/gen_bcrypt.py wrote this file; do not edit it by hand.</auto-generated>
using System.Runtime.CompilerServices;

namespace Conduit;

internal static unsafe partial class BcryptCore
{
    // Blowfish is a chain: every round needs the result of the one before, so one hash leaves most of a core idle
    // (about 10 cycles of latency per round, against 4 or 5 cycles of real work). Running several independent hashes
    // in lockstep, round by round, lets the processor overlap them. Each ExpandN below does one EksBlowfish
    // key-expansion step for N hashes at once: state i lives at st + i * StateWords (18 P words, then the S-boxes),
    // its key at key + i * 18. A lane's P[n] is s[n - 18], with s the start of its S-boxes.
"""]
    for n in range(1, MAX_LANES + 1):
        out.append(f"""
    /// <summary>One key-expansion step (P ^= key, then re-encrypt the whole state) for {n} hash{'es' if n > 1 else ''} at once.</summary>
    [MethodImpl(MethodImplOptions.AggressiveOptimization)]
    private static void Expand{n}(uint* st, uint* key)
    {{""")
        for k in range(n):
            out.append(f"        uint* s{k} = st + {k} * StateWords + 18;")
        out.append("        for (var i = 0; i < 18; i++)\n        {")
        for k in range(n):
            out.append(f"            s{k}[i - 18] ^= key[{k * 18} + i];")
        out.append("        }")
        out.append("        " + " ".join(f"uint l{k} = 0, r{k} = 0;" for k in range(n)))
        out.append("        for (var i = -18; i < StateWords - 18; i += 2)\n        {")
        for k in range(n):
            out.append(f"            l{k} ^= s{k}[-18];")
        for rnd in range(1, 17):
            for k in range(n):
                if rnd % 2:
                    out.append(f"            r{k} ^= {f(k, f'l{k}')} ^ s{k}[{rnd - 18}];")
                else:
                    out.append(f"            l{k} ^= {f(k, f'r{k}')} ^ s{k}[{rnd - 18}];")
        for k in range(n):
            out.append(f"            {{ var t = r{k} ^ s{k}[-1]; r{k} = l{k}; l{k} = t; }}")
            out.append(f"            s{k}[i] = l{k}; s{k}[i + 1] = r{k};")
        out.append("        }\n    }")
        out.append(f"""
    /// <summary>The main loop of bcrypt for {n} hash{'es' if n > 1 else ''}: 2^cost times, expand with the key, then with the salt.</summary>
    [MethodImpl(MethodImplOptions.AggressiveOptimization)]
    private static void Loop{n}(uint* st, uint* key, uint* saltKey, int iterations)
    {{
        for (var it = 0; it < iterations; it++)
        {{
            Expand{n}(st, key);
            Expand{n}(st, saltKey);
        }}
    }}""")
    out.append(f"""
    /// <summary>The most hashes one thread runs at once.</summary>
    internal const int MaxLanes = {MAX_LANES};

    /// <summary>The main loop for 1..MaxLanes hashes.</summary>
    private static void RunLoop(int lanes, uint* st, uint* key, uint* saltKey, int iterations)
    {{
        switch (lanes)
        {{""")
    for n in range(1, MAX_LANES + 1):
        out.append(f"            {'case' if n < MAX_LANES else 'default:'} {n if n < MAX_LANES else ''}{':' if n < MAX_LANES else ''} Loop{n}(st, key, saltKey, iterations); break;".replace("default:  ","default: ").replace("default: Loop","default: Loop"))
    out.append("        }\n    }\n}\n")
    return "\n".join(out)


if __name__ == "__main__":
    words = pi_words(WORDS)
    assert words[0] == 0x243F6A88 and words[17] == 0x8979FB1B and words[18] == 0xD1310BA6 and words[-1] == 0x3AC372E6, "pi digits are wrong"
    open(os.path.join(ROOT, "BlowfishConstants.g.cs"), "w").write(constants_file(words))
    open(os.path.join(ROOT, "BcryptLanes.g.cs"), "w").write(lanes_file())
    print(f"wrote BlowfishConstants.g.cs ({len(words)} words) and BcryptLanes.g.cs ({MAX_LANES} lane variants)")
