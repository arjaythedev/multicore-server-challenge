#!/usr/bin/env python3
"""Generate test candidates scheduling independent amd64 S-box loads together."""
from pathlib import Path

root = Path(__file__).parent
out = ['''// Code generated by interleave_generate.py; DO NOT EDIT.
//go:build amd64 && !purego

#include "textflag.h"
#include "go_asm.h"
''']
for width in (2, 4):
    regs = [('R8', 'R9'), ('R10', 'R11'), ('R12', 'R13'), ('R14', 'R15')][:width]
    temps = ['AX', 'BX', 'CX', 'DX'][:width]
    out += [f'TEXT ·expandAsm{width}(SB), NOSPLIT, $8-16', 'MOVQ c+0(FP), SI',
            'MOVQ words+8(FP), DI', 'XORQ R8, R8', f'key{width}:']
    for k in range(width):
        out += [f'MOVL {k*72}(DI)(R8*4), AX', f'XORL AX, {k*4168}(SI)(R8*4)']
    out += ['INCQ R8', 'CMPQ R8, $18', f'JNE key{width}', 'MOVQ $0, offset-8(SP)']
    for left, right in regs:
        out += [f'XORL {left}, {left}', f'XORL {right}, {right}']
    out += [f'block{width}:']
    for k, (left, _) in enumerate(regs):
        out += [f'XORL state_p+{k*4168}(SI), {left}']
    for round in range(1, 17):
        for box, shift, operation in [('s0', 24, 'MOVL'), ('s1', 16, 'ADDL'), ('s2', 8, 'XORL'), ('s3', 0, 'ADDL')]:
            for k, (left, right) in enumerate(regs):
                source = left if round % 2 else right
                out += [f'MOVL {source}, DI']
                if shift:
                    out += [f'SHRL ${shift}, DI']
                if shift != 24:
                    out += ['ANDL $255, DI']
                out += [f'{operation} state_{box}+{k*4168}(SI)(DI*4), {temps[k]}']
        for k, (left, right) in enumerate(regs):
            target = right if round % 2 else left
            out += [f'XORL state_p+{k*4168+round*4}(SI), {target}', f'XORL {temps[k]}, {target}']
    out += ['MOVQ offset-8(SP), DI']
    for k, (left, right) in enumerate(regs):
        out += [f'XORL state_p+{k*4168+68}(SI), {right}', f'XCHGL {left}, {right}',
                f'MOVL {left}, {k*4168}(SI)(DI*1)', f'MOVL {right}, {k*4168+4}(SI)(DI*1)']
    out += ['ADDQ $8, DI', 'MOVQ DI, offset-8(SP)', 'CMPQ DI, $state__size', f'JNE block{width}', 'RET']
(root / 'interleave_amd64.s').write_text('\n'.join(out)+'\n')

source = (root / 'lanes_generated.go').read_text()
go = ['''// Code generated by interleave_generate.py; DO NOT EDIT.
//go:build amd64 && !purego

package bcryptlane

import "encoding/binary"
''']
for width in (2, 4):
    if width == 4:
        go += [f'//go:noescape\nfunc expandAsm{width}(c *[{width}]state, words *[{width}][18]uint32)']
    start = source.index(f'func Sum{width}(')
    opening = source.index('{', start)
    depth, end = 1, opening+1
    while depth:
        depth += (source[end] == '{') - (source[end] == '}')
        end += 1
    fn = source[start:end].replace(f'func Sum{width}(', f'func sumAsm{width}(')
    fn = fn.replace(f'expand{width}(&st,', f'expandAsm{width}(&st,')
    if width == 4:
        go += [fn]
    if width == 2:
        pair = fn.replace('func sumAsm2(', 'func Pair(')
        (root / 'pair_amd64.go').write_text('''// Code generated by interleave_generate.py; DO NOT EDIT.
//go:build !purego

package bcryptlane

import "encoding/binary"

//go:noescape
func expandAsm2(c *[2]state, words *[2][18]uint32)

'''+pair+'\n')
(root / 'interleave_generated_test.go').write_text('\n\n'.join(go)+'\n')
