from typing import Protocol, Any, Optional, List, Tuple, Sequence


class CryptoPort(Protocol):
    """Outbound port for hashing, token signing and token verification."""

    def hash_password(self, password: str) -> str: ...

    def verify_password(self, password: str, password_hash: str) -> bool: ...

    def issue_token(self, user_id: int) -> str: ...

    def verify_token(self, token: str) -> int:
        """Return the user id, or raise on invalid/expired/mismatched alg."""


# List rows are plain tuples in these column orders (a dict per row cost as much as decoding it).
# Timestamps everywhere are API strings: RFC 3339 UTC with milliseconds, e.g. 2026-10-24T01:02:03.456Z.
ARTICLE_ROW = ("id", "slug", "title", "description", "created_at", "updated_at", "tag_list",
               "favorites_count", "favorited", "username", "bio", "image", "following")
COMMENT_ROW = ("id", "body", "created_at", "updated_at", "username", "bio", "image", "following")


class QueryPort(Protocol):
    """A read a handler waits on with `value = yield query`: the server runs it without blocking its worker (or
    `run()` executes it in place). The value is what the repository method without `q_` returns."""

    def run(self) -> Any: ...


class ArticleRepositoryPort(Protocol):
    """Outbound port for all Conduit SQL. Concrete adapter: psycopg.
    `q_<name>` methods return the read `<name>` as a QueryPort, for generator handlers."""

    def register_user(self, username: str, email: str, password_hash: str) -> dict: ...
    def find_user_by_email(self, email: str) -> Optional[dict]: ...
    def find_user_by_id(self, user_id: int) -> Optional[dict]: ...
    def update_user(self, user_id: int, fields: dict) -> Optional[dict]: ...
    def find_profile(self, viewer: int, username: str) -> Optional[dict]: ...
    def follow(self, follower_id: int, followee_id: int) -> None: ...
    def unfollow(self, follower_id: int, followee_id: int) -> None: ...
    def list_tags(self) -> List[str]: ...
    def list_articles(
        self,
        viewer: int,
        limit: int,
        offset: int,
        filter_kind: str = "none",
        filter_value: str = "",
    ) -> Tuple[int, List[tuple]]: ...
    def feed_articles(self, viewer: int, limit: int, offset: int) -> Tuple[int, List[tuple]]: ...
    def list_articles_json(
        self,
        viewer: int,
        limit: int,
        offset: int,
        filter_kind: str = "none",
        filter_value: str = "",
    ) -> bytes:
        """`list_articles` as the finished response body: {"articles": [...], "articlesCount": n}, UTF-8 JSON."""
    def feed_articles_json(self, viewer: int, limit: int, offset: int) -> bytes:
        """`feed_articles` as the finished response body, like `list_articles_json`."""
    def find_article(self, viewer: int, slug: str) -> Optional[dict]: ...
    def find_article_by_id(self, viewer: int, article_id: int) -> Optional[dict]: ...
    def article_for_write(self, slug: str) -> Optional[dict]: ...
    def create_article(
        self, author_id: int, title: str, description: str, body: str, tags: Sequence[str]
    ) -> Optional[int]: ...
    def update_article(self, article_id: int, fields: dict) -> None: ...
    def delete_article(self, article_id: int) -> None: ...
    def favorite(self, viewer: int, article_id: int) -> None: ...
    def unfavorite(self, viewer: int, article_id: int) -> None: ...
    def list_comments(self, viewer: int, article_id: int) -> List[tuple]: ...
    def list_comments_by_slug(self, viewer: int, slug: str) -> Optional[List[tuple]]:
        """None when the article doesn't exist."""
    def q_find_user_by_id(self, user_id: int) -> QueryPort: ...
    def q_find_profile(self, viewer: int, username: str) -> QueryPort: ...
    def q_list_tags(self) -> QueryPort: ...
    def q_list_articles_json(
        self,
        viewer: int,
        limit: int,
        offset: int,
        filter_kind: str = "none",
        filter_value: str = "",
    ) -> QueryPort: ...
    def q_feed_articles_json(self, viewer: int, limit: int, offset: int) -> QueryPort: ...
    def q_find_article(self, viewer: int, slug: str) -> QueryPort: ...
    def q_list_comments_by_slug(self, viewer: int, slug: str) -> QueryPort: ...
    def create_comment(self, author_id: int, article_id: int, body: str) -> dict: ...
    def comment_for_write(self, slug: str, comment_id: int) -> Optional[dict]: ...
    def delete_comment(self, comment_id: int) -> None: ...
