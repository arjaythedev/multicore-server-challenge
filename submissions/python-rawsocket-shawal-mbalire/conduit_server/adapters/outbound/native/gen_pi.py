"""Blowfish's initial P-array and S-boxes: the fractional hex digits of pi, 18 + 4*256 32-bit words, as a C header."""
import sys
WORDS = 18 + 4 * 256
bits = WORDS * 32 + 64
one = 1 << bits
def atan_inv(x):
    s, t, n, sign = 0, one // x, 1, 1
    x2 = x * x
    while t:
        s += sign * (t // n)
        t //= x2; n += 2; sign = -sign
    return s
pi = 16 * atan_inv(5) - 4 * atan_inv(239)
frac = pi - 3 * one
words = [(frac >> (bits - 32 * (i + 1))) & 0xFFFFFFFF for i in range(WORDS)]
assert words[0] == 0x243F6A88 and words[17] == 0x8979FB1B and words[18] == 0xD1310BA6 and words[-1] == 0x3AC372E6, [hex(w) for w in (words[0], words[17], words[18], words[-1])]
out = ["/* generated by gen_pi.py: the fractional hex digits of pi (Blowfish's initial state) */",
       "static const uint32_t BF_INIT[%d] = {" % WORDS]
for i in range(0, WORDS, 6):
    out.append("  " + ", ".join("0x%08x" % w for w in words[i:i + 6]) + ",")
out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("ok", hex(words[0]), hex(words[-1]))
